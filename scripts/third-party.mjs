// Regenerates the dependency lists at the end of THIRD_PARTY.md from package-lock.json and
// `cargo metadata`, and checks every npm license against the allow list in deny.toml (cargo-deny
// checks the Rust crates). `node scripts/third-party.mjs` rewrites the file; `--check` fails
// instead if the file is out of date or an npm license is not allowed.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
// Git may check text files out with CRLF on Windows; compare and write with LF.
const read = (path) => readFileSync(new URL(path, root), "utf8").replaceAll("\r\n", "\n");
const MARKER = "<!-- Everything below is generated by scripts/third-party.mjs. Do not edit by hand. -->";

// Licenses from deny.toml's `allow = [...]`, so npm and Rust share one list.
function allowedLicenses() {
  const list = read("deny.toml").match(/^allow\s*=\s*\[([^\]]*)\]/m);
  if (!list) throw new Error("deny.toml has no allow = [...] list");
  return new Set([...list[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]));
}

// True when an SPDX expression such as "(MIT OR Apache-2.0) AND Unicode-3.0" can be met with
// allowed licenses alone. OR needs one side, AND needs both; "A WITH B" is one license id.
function satisfies(expression, allowed) {
  const tokens = expression.replace(/[()]/g, " $& ").trim().split(/\s+/);
  let i = 0;
  let malformed = false;
  const atom = () => {
    if (tokens[i] === "(") {
      i++;
      const ok = or();
      if (tokens[i] !== ")") malformed = true;
      i++;
      return ok;
    }
    let id = tokens[i++];
    if (tokens[i] === "WITH") {
      id += ` WITH ${tokens[i + 1]}`;
      i += 2;
    }
    return allowed.has(id);
  };
  const and = () => {
    let ok = atom();
    while (tokens[i] === "AND") {
      i++;
      ok = atom() && ok;
    }
    return ok;
  };
  const or = () => {
    let ok = and();
    while (tokens[i] === "OR") {
      i++;
      ok = and() || ok;
    }
    return ok;
  };
  return or() && !malformed && i === tokens.length;
}

function npmPackages() {
  const lock = JSON.parse(read("package-lock.json"));
  return Object.entries(lock.packages)
    .filter(([path]) => path !== "")
    .map(([path, p]) => ({
      name: path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: p.version,
      license: p.license ?? "",
      // devOptional: a devDependency that is also an optional peer of a dependency (@types/react).
      dev: Boolean(p.dev || p.devOptional),
      optional: Boolean(p.optional),
    }));
}

function rustCrates() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--manifest-path", "src-tauri/Cargo.toml"], {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    }),
  );
  // Path dependencies (source null) are tricky3D itself.
  return meta.packages.filter((p) => p.source !== null).map((p) => ({ name: p.name, version: p.version, license: p.license ?? `see ${p.license_file}` }));
}

const byName = (a, b) => (a.name === b.name ? a.version.localeCompare(b.version, "en", { numeric: true }) : a.name < b.name ? -1 : 1);
const cell = (s) => s.replaceAll("|", "\\|");

function npmTable(packages) {
  const rows = packages.sort(byName).map((p) => `| ${p.name} | ${p.version} | ${cell(p.license)} | ${p.optional ? "optional" : ""} |`);
  return ["| Package | Version | License | Note |", "| --- | --- | --- | --- |", ...rows].join("\n");
}

function rustTable(crates) {
  const rows = crates.sort(byName).map((c) => `| ${c.name} | ${c.version} | ${cell(c.license)} |`);
  return ["| Crate | Version | License |", "| --- | --- | --- |", ...rows].join("\n");
}

function generated() {
  const npm = npmPackages();
  const app = npm.filter((p) => !p.dev);
  const dev = npm.filter((p) => p.dev);
  const crates = rustCrates();
  return `${MARKER}

## Full dependency list

Every package that \`npm ci\` installs and every crate in \`src-tauri/Cargo.lock\`, with the license its package metadata declares. Run \`node scripts/third-party.mjs\` after changing dependencies; CI fails when this list is out of date.

### npm packages under \`dependencies\` (${app.length})

These include the packages manifold-3d's command-line tool pulls in. tricky3D bundles only the files it imports (see above).

${npmTable(app)}

### npm packages under \`devDependencies\` (${dev.length})

Build and test tools. None of them ship in the app.

${npmTable(dev)}

### Rust crates (${crates.length})

The list covers every platform. Each build compiles only the crates for its own platform, and build scripts and macros run at compile time without being shipped.

${rustTable(crates)}
`;
}

const check = process.argv.includes("--check");
const current = read("THIRD_PARTY.md");
const at = current.indexOf(MARKER);
const next = `${(at === -1 ? current : current.slice(0, at)).trimEnd()}\n\n${generated()}`;

const allowed = allowedLicenses();
const refused = npmPackages().filter((p) => !satisfies(p.license, allowed));
for (const p of refused) console.error(`npm package ${p.name}@${p.version} has a license deny.toml does not allow: "${p.license}"`);

if (check) {
  if (next !== current) console.error("THIRD_PARTY.md is out of date. Run: node scripts/third-party.mjs");
  if (next !== current || refused.length > 0) process.exit(1);
  console.log("THIRD_PARTY.md is up to date and every npm license is allowed.");
} else {
  writeFileSync(new URL("THIRD_PARTY.md", root), next);
  console.log("THIRD_PARTY.md updated.");
  if (refused.length > 0) process.exit(1);
}
